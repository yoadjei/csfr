"""No result number in the manuscript's prose is typed by hand.

Round 1 typed its numbers and locked each with a test here, and they drifted
anyway: the external prior's largest margin was reported as 8.4 dB when the
sweep said 9.08, and the CF1 L1 standard deviations were off by 0.5. In round 2
every number in running text is a macro that scripts/render_numbers_v2.py
generates from its source (tests/test_numbers_v2.py fails if the generated file
is stale), and every results table is generated by scripts/render_tables_v2.py.
This module enforces that rule mechanically: outside the generated tables, the
abstract and the sections that report or interpret results contain no decimal
number. Integers are not checked (they include section numbers and sizes), so
an integer claim must still go through a macro by discipline.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
TEX = ROOT / "paper" / "paper2_reconstruction.tex"
DECIMAL = re.compile(r"(?<![\w.\\])\d+\.\d+(?!\s*(?:pt|em|ex|cm|mm|in)\b)")   # not a TeX length
SECTIONS = {
    "abstract": (r"\begin{abstract}", r"\end{abstract}"),
    "results": (r"\section{Results}", r"\section{Discussion}"),
    "discussion": (r"\section{Discussion}", r"\section{Scope and Limitations}"),
    "conclusion": (r"\section{Conclusion}", r"\section*{Acknowledgements}"),
}
REWRITE_PENDING = pytest.mark.xfail(strict=True, reason="still the round-1 text; rewritten when the "
                                                        "round-2 results exist, then remove this marker")


def prose(tex: str, name: str) -> str:
    """One section without its generated tables and comments."""
    start, end = SECTIONS[name]
    text = tex[tex.index(start):tex.index(end)]
    text = re.sub(r"% BEGIN AUTO (\S+)\n.*?% END AUTO \1", "", text, flags=re.S)
    return re.sub(r"(?<!\\)%.*", "", text)


def test_prose_strips_generated_tables_and_comments():
    tex = ("\\section{Results}\nCSFR leads by \\deltaMacro\\,dB.\n% BEGIN AUTO X\n1.25 & 3.5 \\\\\n"
           "% END AUTO X\n% a comment with 2.5\n\\setlength{\\tabcolsep}{3.5pt}\n50\\% of 0.75\n"
           "\\section{Discussion}")
    assert DECIMAL.findall(prose(tex, "results")) == ["0.75"]


@pytest.mark.parametrize("name", ["abstract", "results", "discussion",
                                  pytest.param("conclusion", marks=REWRITE_PENDING)])
def test_no_hand_typed_decimals(name):
    hits = DECIMAL.findall(prose(TEX.read_text(encoding="utf-8"), name))
    assert not hits, f"{name} types numbers by hand ({hits[:5]}); generate them in render_numbers_v2.py"
